def build_guide(spec: dict, build: dict, size_mm, quote: dict | None) -> str:
    L = [f"# DEV FIXTURE: {spec['name']} build guide", "", BANNER, f"{spec['tagline']}.", "",
         "![Assembled Moon Hug, front three-quarter view](manual/assembled.png)", "",
         f"Size about {size_mm[0]:.0f} W x {size_mm[1]:.0f} D x {size_mm[2]:.0f} H mm (CAD bounding box including the feet "
         "and the button).", "",
         "![Exploded view of every part](manual/exploded.png)", "",
         "## What you need", ""]
    for r in build["purchased"]:
        L.append(f"- {r['quantity']} x {r['name']}" + (" (soldering needed)" if r.get("requiresSoldering") else ""))
    for p in build["printed"]:
        L.append(f"- {p['name']} printed in {p['material']}" + (f", about {p['grams']:.0f} g" if p.get("grams") else ""))
    L += ["", "Tools: FDM printer, soldering iron (inserts and the speaker lead), 2 mm hex key, flush cutters, tweezers.", ""]
    for k, s in enumerate(build["steps"], 1):
        L += [f"## Step {k}. {s['title']}", "", s["instruction"], ""]
        for v in s.get("visuals", []):
            L += [f"![{v['alt']}]({v['path']})", "", f"*{v['caption']}*", ""]
        L += [f"**Expected:** {s['expected']}", ""]
    L += ["## Wiring", "", "![Wiring diagram: backplane ports to modules](manual/wiring.png)", "",
          "| From | To | Cable | Colour | Net |", "|---|---|---|---|---|"]
    for c in build["wiring"]["connections"]:
        L.append(f"| `{c['from']}` | `{c['to']}` | {c.get('via') or ''} | {c.get('color') or ''} | {c.get('note') or ''} |")
    L += ["", "## Physical checks still needed", ""]
    for t in build["tests"]:
        if t["kind"] == "physical":
            L.append(f"- [ ] **{t['title']}**: {t['expected']} (not run)")
    if quote:
        d = quote["delivered_price_inr"]
        L += ["", "## Price", "", f"Delivered price estimate (one-off pilot): INR {d['pilot_one_off']:,}; steady state: INR "
              f"{d['steady_state']:,}. Status: {quote['status_label']}. Not binding; see `order/quote.json`.", ""]
    L += ["", "No physical test has been run on this design. Every rendered image is of the CAD model, not a photograph.", ""]
    return "\n".join(L)


