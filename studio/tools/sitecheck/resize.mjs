import { chromium } from "/opt/gs/pw/node_modules/playwright/index.mjs";
import path from "node:path";
import { spawn } from "node:child_process";
const here = path.dirname(new URL(import.meta.url).pathname);
const siteDir = path.resolve(here, "../../site");
const server = spawn("python3", ["-m", "http.server", "8767", "--bind", "127.0.0.1"], { cwd: siteDir, stdio: "ignore" });
await new Promise(r => setTimeout(r, 800));
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--enable-webgl"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; page.on("pageerror", e => errs.push(String(e)));
await page.goto("http://127.0.0.1:8767/index.html", { waitUntil: "networkidle" });
const before = await page.evaluate(() => document.documentElement.className);
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(2500);
await page.waitForLoadState("networkidle").catch(() => {});
const after = await page.evaluate(() => document.documentElement.className);
await page.evaluate(() => document.querySelector("#story-pin, .story-pin")?.scrollIntoView());
await page.waitForTimeout(1500);
await page.screenshot({ path: path.resolve(here, "../../_out/site-test/resize-390.png") });
await page.setViewportSize({ width: 1440, height: 900 });
await page.waitForTimeout(2500);
const back = await page.evaluate(() => document.documentElement.className);
console.log(JSON.stringify({ before, after, back, errs }));
await browser.close(); server.kill();
