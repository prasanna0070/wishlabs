def fw_version(engine_version: str, spec: dict) -> tuple[str, str]:
    raw = json.dumps({k: spec.get(k) for k in ("slug", "behaviour", "features", "electronics")}, sort_keys=True, default=str)
    h = hashlib.sha256(raw.encode()).hexdigest()
    return f"{engine_version}+{h[:8]}", h[:12]


def _copytree(src: Path, dst: Path) -> list[Path]:
    written = []
    for p in sorted(src.rglob("*")):
        if p.is_dir() or "__pycache__" in p.parts:
            continue
        rel = p.relative_to(src)
        t = dst / rel
        t.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(p, t)
        written.append(t)
    return written


def write_project(fw: Path, spec: dict, template: str, settings: dict, binding: Binding, engine_version: str,
                  ota_pubkey_pem: str = "") -> dict[str, Any]:
    """Create or refresh <out>/firmware. Generated parts are replaced; build outputs are left for the build step."""
    fw.mkdir(parents=True, exist_ok=True)
    for sub in ("src", "include", "lib", "test", "data", "scripts"):
        if (fw / sub).exists():
            shutil.rmtree(fw / sub)
    app = TEMPLATES / "apps" / template / f"app_{template}.cpp"
    if not app.exists():
        raise FileNotFoundError(f"no firmware template for {template}")
    files = []
    files += _copytree(COMMON / "src", fw / "src")
    files += _copytree(COMMON / "lib", fw / "lib")
    for suite in ("shims",) + SHARED_SUITES:
        files += _copytree(COMMON / "test" / suite, fw / "test" / suite)
    app_tests = TEMPLATES / "apps" / template / "test"
    if app_tests.exists():
        files += _copytree(app_tests, fw / "test")
    files += _copytree(COMMON / "data", fw / "data")
    shutil.copyfile(app, fw / "src" / app.name)
    files.append(fw / "src" / app.name)
    version, build_id = fw_version(engine_version, spec)
    (fw / "include").mkdir(exist_ok=True)
    (fw / "scripts").mkdir(exist_ok=True)
    out = {
        "include/pins.h": pins_h(binding),
        "include/hardware.h": hardware_h(binding),
        "include/config.h": config_h(spec, template, settings, binding, version, build_id, ota_pubkey_pem),
        "include/parent_page.h": page_header((fw / "data" / "parent.html").read_text(encoding="utf-8")),
        "partitions.csv": PARTITIONS_8MB,
        "sdkconfig.production.defaults": SDKCONFIG_PRODUCTION,
        "platformio.ini": platformio_ini(spec, template, binding),
        "scripts/prebuild.py": EMBED_SCRIPT,
    }
    for rel, text in out.items():
        p = fw / rel
        p.write_text(text, encoding="utf-8")
        files.append(p)
    return {"version": version, "build_id": build_id, "files": [str(p.relative_to(fw)) for p in files]}


