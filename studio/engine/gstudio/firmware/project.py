def page_header(html: str) -> str:
    if ')GSHTML"' in html:
        raise ValueError('parent.html must not contain )GSHTML"')
    return ("// GENERATED from data/parent.html by scripts/prebuild.py; edit the HTML, not this file.\n"
            "#pragma once\n"
            'static const char GS_PARENT_PAGE[] = R"GSHTML(' + html + ')GSHTML";\n')


def c_str(s: str) -> str:
    """C string literal; non-ASCII as UTF-8 octal escapes."""
    out = []
    for b in str(s).encode("utf-8"):
        c = chr(b)
        if c in '"\\':
            out.append("\\" + c)
        elif 32 <= b < 127 and c != "?":
            out.append(c)
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def ap_prefix(name: str) -> str:
    """Hotspot name prefix from whole words of the product name, at most 12 characters: "Momo the Bedtime
    Robot" -> "MomoBedtime". Filler words are skipped; non-ASCII letters are dropped."""
    words = [re.sub(r"[^A-Za-z0-9]", "", w) for w in str(name).split()]
    words = [w for w in words if w]
    keep = [w for w in words if w.lower() not in {"the", "a", "an", "of", "and", "my"}] or words
    out = ""
    for w in keep:
        if out and len(out) + len(w) > 12:
            break
        out += w[:1].upper() + w[1:] if out else w
    return out[:12] or "Gadget"


def slug_ok(slug: str) -> str:
    s = re.sub(r"[^a-z0-9-]", "-", str(slug).lower()).strip("-")[:24].strip("-")
    return s or "gadget"


def _pct255(p: int) -> int:
    return max(1, min(255, round(int(p) * 255 / 100)))


