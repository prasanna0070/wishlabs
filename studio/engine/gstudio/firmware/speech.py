"""Story-card audio checks (MAJ-18), run whenever the story audio is synthesised.

1. Every WAV on the card is parsed by the firmware's own gs::wav_parse (lib/gs_core/src/gs_audio_math.cpp),
   compiled once as a host tool. A file fails on any mismatch in sample rate, channels, sample width or length.
2. Every story segment, name clip and prompt is transcribed with Gemini on Vertex and compared with the text it
   was synthesised from: word error rate (WER) for segments and prompts, exact match for names.
3. The result goes to firmware/speech-roundtrip.json with the voice and models per file and the scope line
   "synthetic voice, no speaker or child tested".

Transcripts are cached by the WAV's SHA-256 and the model, so a rebuild with the same audio makes no new calls.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import struct
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any, Callable, Optional

SCOPE = "synthetic voice, no speaker or child tested"
WER_LIMIT = 0.15
STT_MODEL = os.environ.get("GS_STT_MODEL", "gemini-3.5-flash")
EXPECT = {"sample_rate": 24000, "channels": 1, "bits": 16}

WAVCHECK_MAIN = r'''// Host tool: runs the firmware's gs::wav_parse on files. Generated by gstudio.firmware.speech.
#include <stdio.h>
#include <stdint.h>
#include "gs_audio_math.h"
int main(int argc, char** argv) {
  for (int i = 1; i < argc; ++i) {
    FILE* f = fopen(argv[i], "rb");
    if (!f) { printf("{\"file\":\"%s\",\"ok\":false,\"error\":\"open\"}\n", argv[i]); continue; }
    uint8_t head[512];
    const size_t got = fread(head, 1, sizeof(head), f);
    fseek(f, 0, SEEK_END);
    const long size = ftell(f);
    fclose(f);
    gs::WavInfo wi;
    const bool ok = gs::wav_parse(head, got, (uint32_t)size, &wi);
    printf("{\"file\":\"%s\",\"parsed\":%s,\"sample_rate\":%u,\"channels\":%u,\"bits\":%u,\"data_offset\":%u,"
           "\"data_bytes\":%u,\"file_bytes\":%ld}\n", argv[i], ok ? "true" : "false", (unsigned)wi.sample_rate,
           (unsigned)wi.channels, (unsigned)wi.bits, (unsigned)wi.data_offset, (unsigned)wi.data_bytes, size);
  }
  return 0;
}
'''


# ------------------------------------------------------------------ WAV parsing
def build_wavcheck(core_src: Path, cache: Path) -> Optional[Path]:
    """Compiles the host tool from the firmware's gs_audio_math.cpp (once per source version). None without a compiler."""
    cxx = shutil.which("c++") or shutil.which("g++") or shutil.which("clang++")
    src = core_src / "gs_audio_math.cpp"
    if not cxx or not src.exists():
        return None
    h = hashlib.sha256(src.read_bytes() + (core_src / "gs_audio_math.h").read_bytes() + WAVCHECK_MAIN.encode()).hexdigest()[:16]
    exe = cache / f"wavcheck-{h}"
    if exe.exists():
        return exe
    cache.mkdir(parents=True, exist_ok=True)
    main = cache / f"wavcheck-{h}.cpp"
    main.write_text(WAVCHECK_MAIN)
    tmp = exe.with_suffix(".tmp")
    r = subprocess.run([cxx, "-O2", "-std=c++17", "-I", str(core_src), str(main), str(src), "-o", str(tmp)],
                       capture_output=True, text=True, timeout=120)
    if r.returncode != 0 or not tmp.exists():
        return None
    tmp.replace(exe)
    return exe


def wav_check_python(path: Path) -> dict:
    """An independent RIFF reader (used by the tests and when no compiler is present)."""
    b = Path(path).read_bytes()
    out: dict[str, Any] = {"file": str(path), "parsed": False, "file_bytes": len(b)}
    if len(b) < 12 or b[:4] != b"RIFF" or b[8:12] != b"WAVE":
        return out | {"ok": False}
    pos, fmt = 12, None
    while pos + 8 <= len(b):
        cid, size = b[pos:pos + 4], struct.unpack("<I", b[pos + 4:pos + 8])[0]
        if cid == b"fmt ":
            fmt = struct.unpack("<HHIIHH", b[pos + 8:pos + 24])
        if cid == b"data":
            if not fmt:
                break
            data = min(size, len(b) - pos - 8) if size not in (0, 0xFFFFFFFF) else len(b) - pos - 8
            out.update({"parsed": fmt[0] == 1, "channels": fmt[1], "sample_rate": fmt[2], "bits": fmt[5],
                        "data_offset": pos + 8, "data_bytes": data})
            break
        pos += 8 + size + (size & 1)
    return out | {"ok": _row_ok(out)}


def _row_ok(r: dict, expect: dict = EXPECT) -> bool:
    return bool(r.get("parsed")) and r.get("sample_rate") == expect["sample_rate"] and r.get("channels") == expect["channels"] \
        and r.get("bits") == expect["bits"] and r.get("data_bytes", 0) > 0 \
        and r.get("data_offset", 0) + r.get("data_bytes", 0) == r.get("file_bytes")


def check_card(sd: Path, core_src: Path, cache: Path) -> dict:
    """Parses every WAV on the card with the firmware's parser. Each row says why it failed."""
    files = sorted(p for p in sd.rglob("*.wav"))
    exe = build_wavcheck(core_src, cache)
    rows: list[dict] = []
    if exe:
        for i in range(0, len(files), 200):
            r = subprocess.run([str(exe)] + [str(p) for p in files[i:i + 200]], capture_output=True, text=True, timeout=120)
            rows += [json.loads(line) for line in r.stdout.splitlines() if line.strip()]
        parser = "firmware gs::wav_parse (lib/gs_core/src/gs_audio_math.cpp) built as a host tool"
    else:
        rows = [wav_check_python(p) for p in files]
        parser = "Python RIFF reader (no C++ compiler on this machine; the firmware parser did not run)"
    for r in rows:
        r["ok"] = _row_ok(r)
        r["file"] = str(Path(r["file"]).relative_to(sd))
        if r["ok"]:
            r["duration_s"] = round(r["data_bytes"] / (r["sample_rate"] * r["channels"] * 2), 2)
        else:
            why = []
            if not r.get("parsed"):
                why.append("not a 16-bit PCM WAV")
            else:
                for k, v in EXPECT.items():
                    if r.get(k) != v:
                        why.append(f"{k} {r.get(k)} (expected {v})")
                if r.get("data_offset", 0) + r.get("data_bytes", 0) != r.get("file_bytes"):
                    why.append("data length does not match the file size")
            r["error"] = "; ".join(why) or "empty"
    bad = [r for r in rows if not r["ok"]]
    return {"parser": parser, "expected": EXPECT, "files": len(rows), "failed": len(bad), "ok": bool(rows) and not bad,
            "rows": rows}


# ------------------------------------------------------------------ transcription and WER
# Spelling variants a transcriber may choose for the same spoken word. Applied to both texts before scoring, and
# listed in the report's method line. Only words that occur in our own story pack are listed.
SPELLING_VARIANTS = {"chug": "chuk", "colour": "color", "neighbours": "neighbors", "baadal": "badal"}


def words(text: str) -> list[str]:
    t = text.lower().replace("’", "'")
    t = re.sub(r"[^a-z0-9' ]+", " ", t)
    out = [w.strip("'") for w in t.split() if w.strip("'")]
    return [SPELLING_VARIANTS.get(w, w) for w in out]


def wer(ref: str, hyp: str) -> float:
    r, h = words(ref), words(hyp)
    if not r:
        return 0.0 if not h else 1.0
    prev = list(range(len(h) + 1))
    for i, rw in enumerate(r, 1):
        cur = [i] + [0] * len(h)
        for j, hw in enumerate(h, 1):
            cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (rw != hw))
        prev = cur
    return round(prev[-1] / len(r), 4)


class GeminiStt:
    """Transcribes a WAV with Gemini on Vertex (global endpoint). Cached by WAV hash + model."""

    def __init__(self, model: str = STT_MODEL, cache: Optional[Path] = None, project: Optional[str] = None):
        from google import genai

        from .tts import DEFAULT_PROJECT

        self.model = model
        self.cache = cache
        proj = project or os.environ.get("GOOGLE_CLOUD_PROJECT") or DEFAULT_PROJECT
        self.client = genai.Client(vertexai=True, project=proj, location="global")

    def __call__(self, path: Path) -> str:
        from google.genai import types

        data = Path(path).read_bytes()
        key = hashlib.sha256(data + self.model.encode()).hexdigest()
        if self.cache:
            hit = self.cache / f"{key}.json"
            if hit.exists():
                return json.loads(hit.read_text())["text"]
        resp = self.client.models.generate_content(
            model=self.model,
            contents=[types.Part.from_bytes(data=data, mime_type="audio/wav"),
                      "Transcribe this audio exactly, word for word, in English. Output only the spoken words."],
            config=types.GenerateContentConfig(temperature=0))
        text = (resp.text or "").strip()
        if self.cache:
            self.cache.mkdir(parents=True, exist_ok=True)
            (self.cache / f"{key}.json").write_text(json.dumps({"model": self.model, "text": text}))
        return text


def roundtrip(sd: Path, stt: Callable[[Path], str], stt_model: str, wav_rows: Optional[list[dict]] = None,
              workers: int = 6) -> dict:
    """Transcribes every segment, name clip and prompt listed in stories.json and scores it."""
    idx = json.loads((sd / "stories.json").read_text(encoding="utf-8"))
    durations = {r["file"]: r.get("duration_s") for r in (wav_rows or [])}
    jobs: list[dict] = []
    for st in idx.get("stories", []):
        for f, text in zip(st["files"], st["segment_text"]):
            jobs.append({"kind": "segment", "story": st["id"], "file": f, "text": text})
    names = [idx.get("default_name"), idx.get("default_friend")] + list(idx.get("names") or [])
    for n in names:
        if n:
            jobs.append({"kind": "name", "file": n["file"], "text": n["name"]})
    for p in idx.get("prompts") or []:
        jobs.append({"kind": "prompt", "file": p["file"], "text": p["text"]})

    def one(j: dict) -> dict:
        row = dict(j, voice=idx.get("voice"), tts_model=idx.get("tts_model"), stt_model=stt_model,
                   duration_s=durations.get(j["file"]))
        p = sd / j["file"]
        if not p.exists():
            return row | {"ok": False, "error": "file missing"}
        try:
            hyp = stt(p)
        except Exception as e:  # recorded honestly; the check fails
            return row | {"ok": False, "error": f"transcription failed: {str(e)[:200]}"}
        row["transcript"] = hyp
        if j["kind"] == "name":
            row["exact"] = words(hyp) == words(j["text"])
            row["ok"] = row["exact"]
        else:
            row["wer"] = wer(j["text"], hyp)
            row["ok"] = row["wer"] <= WER_LIMIT
        row["words"] = len(words(j["text"]))
        return row

    with ThreadPoolExecutor(max_workers=workers) as pool:
        rows = list(pool.map(one, jobs))
    seg = [r for r in rows if r["kind"] == "segment"]
    scored = [r for r in seg if "wer" in r]
    out = {
        "schema": "gadget-speech-roundtrip/1",
        "scope": SCOPE,
        "method": "Each card WAV is transcribed by a speech model and compared with the text it was synthesised from. "
                  "Segments and prompts: word error rate after lower-casing, removing punctuation and mapping these "
                  "spelling variants on both sides: " + ", ".join(f"{a}={b}" for a, b in SPELLING_VARIANTS.items()) +
                  ". Names: exact match.",
        "tts": {"voice": idx.get("voice"), "model": idx.get("tts_model"), "language": idx.get("language")},
        "stt": {"model": stt_model, "provider": "Gemini on Vertex AI"},
        "wer_limit": WER_LIMIT,
        "segments_total": len(seg),
        "segments_passed": sum(1 for r in seg if r.get("ok")),
        "names_exact": f"{sum(1 for r in rows if r['kind'] == 'name' and r.get('ok'))}/{sum(1 for r in rows if r['kind'] == 'name')}",
        "worst_segment_wer": max((r["wer"] for r in scored), default=None),
        "mean_segment_wer": round(sum(r["wer"] for r in scored) / len(scored), 4) if scored else None,
        "rows": rows,
    }
    out["ok"] = bool(rows) and all(r.get("ok") for r in rows)
    return out


def write_report(fw: Path, card: dict, trip: Optional[dict], error: Optional[str] = None) -> dict:
    """firmware/speech-roundtrip.json: the WAV parse results and the transcription round trip."""
    rep = dict(trip) if trip else {"schema": "gadget-speech-roundtrip/1", "scope": SCOPE, "ok": False, "rows": []}
    rep["wav_check"] = card
    if error:
        rep["error"] = error
    rep["ok"] = bool(rep.get("ok")) and bool(card.get("ok"))
    (fw / "speech-roundtrip.json").write_text(json.dumps(rep, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return rep


